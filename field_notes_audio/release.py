def git(arguments: list[str], optional: bool = False) -> str | None:
    result = subprocess.run(
        ["git", *arguments], cwd=audio.ROOT, capture_output=True, text=True, timeout=180
    )
    if result.returncode and not optional:
        raise RuntimeError(
            f"Git {' '.join(arguments[:2])} failed. Check your GitHub login and branch, then repeat the command."
        )
    return (
        (result.stdout if "-z" in arguments else result.stdout.strip())
        if result.returncode == 0
        else None
    )


def release_state() -> dict:
    path = audio.ROOT / "artifacts/audio/release.json"
    return read_object(path) if path.exists() else {}


def dirty_paths() -> list[str]:
    result = git(["status", "--porcelain=v1", "-z", "--untracked-files=all"])
    # Renames and deletions aren't generated by this workflow and are rejected.
    paths = []
    for line in result.split("\0"):
        if not line:
            continue
        if len(line) < 4 or line[:2].strip() not in {"M", "A", "AM", "??"}:
            raise ValueError("Save other Git changes before publishing the audio collection")
        paths.append(line[3:])
    return paths


def assert_clean_or_prepared() -> None:
    saved = release_state().get("files", {})
    for relative in dirty_paths():
        path = audio.ROOT / relative
        if (
            relative not in saved
            or not path.is_file()
            or audio.digest_file(path) != saved[relative]
        ):
            raise ValueError(
                f"Save or commit existing changes before --publish: {relative}. You can still run make-all without --publish."
            )


def publication_remote() -> tuple[str, str]:
    upstream = git(
        ["rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{upstream}"], optional=True
    )
    remote, branch = (
        upstream.split("/", 1) if upstream else ("origin", git(["branch", "--show-current"]))
    )
    url = git(["remote", "get-url", remote])
    if not re.fullmatch(
        r"(?:https://github\.com/|git@github\.com:)mothandgravel/\.github(?:\.git)?", url or ""
    ):
        raise ValueError(
            "Publication requires this checkout's GitHub remote to be mothandgravel/.github"
        )
    if not branch:
        raise ValueError("Check out a branch before publishing; detached HEAD cannot be published")
    return remote, branch


def script_candidate(root: Path, note: dict) -> tuple[str, str]:
    """Keep the essay and study limits; omit decorative context sidebars."""

    class ScriptReader(audio.ProseReader):
        def __init__(self):
            super().__init__()
            self.asides = []

        def handle_starttag(self, tag, attrs):
            if tag == "aside":
                hidden = "native-study-status" not in dict(attrs).get("class", "").split()
                self.asides.append(hidden)
                self.parts.append("\n\n")
                if hidden:
                    self.hidden += 1
            super().handle_starttag(tag, attrs)

        def handle_endtag(self, tag):
            super().handle_endtag(tag)
            if tag == "aside":
                if self.asides.pop():
                    self.hidden = max(0, self.hidden - 1)
                self.parts.append("\n\n")
            elif not self.hidden and tag in {"strong", "span", "code"}:
                self.parts.append(" ")

    source = audio.source_article(root, note)
    reader = ScriptReader()
    reader.feed(source)
    reader.close()
    body = re.sub(r"(?<=[.!?])(?=[A-Z])", " ", reader.text())
    body = (
        body.replace(" ↗", "")
        .replace(" × ", " by ")
        .replace(" px ", " pixels ")
        .replace(" ms ", " milliseconds ")
    )
    body = re.sub(r"(\d+(?:\.\d+)?):1\b", r"\1 to one.", body)
    script = (
        f"Moth and Gravel. Field Note {int(note['id'])}. {note['title']}\n\n"
        "An AI-narrated edition of the published note.\n\n"
        + body
        + "\n\nYou have been listening to Moth and Gravel Field Notes. The written edition is at moth and gravel dot com.\n"
    )
    return source, script


def sync_catalog() -> list[str]:
    """Freeze complete prose for newly published notes; never refresh stale scripts."""
    root = audio.ROOT
    path = root / "audio/episodes.json"
    episodes = json.loads(path.read_text(encoding="utf-8"))
    existing = {
        e.get("publication", {}).get("note_id")
        for e in episodes
        if e.get("publication", {}).get("kind") == "note"
    }
    base = next(e for e in episodes if e["id"] == "note-001")
    added = []
    for note in audio.catalog(root).values():
        if note["id"] in existing:
            continue
        if not re.fullmatch(r"\d{3,}", note["id"]):
            raise ValueError("Invalid field note ID")
        identifier = "note-" + note["id"]
        if any(e["id"] == identifier for e in episodes):
            raise ValueError("An existing episode ID has no primary publication mapping")
        source, script = script_candidate(root, note)
        target = root / "audio/scripts" / (identifier + ".txt")
        if target.exists():
            raise ValueError(
                "A script candidate already exists; review it before adding the episode"
            )
        target.write_text(script)
        episodes.append(
            {
                **base,
                "id": identifier,
                "title": note["title"],
                "script": "scripts/" + identifier + ".txt",
                "notes": [note["id"]],
                "source_sha256": {note["id"]: audio.digest(source.encode())},
                "publication": {"kind": "note", "note_id": note["id"]},
            }
        )
        added.append(identifier)
    if added:
        audio.write_json(path, episodes)
        print("Prepared source-preserving scripts: " + ", ".join(added))
    return added


def prepare_publication(completed: list[tuple[dict, Path]]) -> list[dict]:
    root = audio.ROOT
    notes = audio.catalog(root)
    existing_path = root / "docs/assets/audio/episodes.json"
    existing = (
        {e["id"]: e for e in json.loads(existing_path.read_text(encoding="utf-8"))}
        if existing_path.exists()
        else {}
    )
    entries, assets = [], {}
    published_at = datetime.now(timezone.utc).isoformat()
    # Read and verify every recording before writing the public manifest or HTML.
    for episode, directory in completed:
        recording = directory.parent.parent
        metadata = json.loads((recording / "episode.json").read_text(encoding="utf-8"))
        capmeta = json.loads((directory / "captions.json").read_text(encoding="utf-8"))
        content = (recording / "episode.mp3").read_bytes()
        audio_hash = audio.digest(content)
        if (
            metadata.get("id") != episode["id"]
            or metadata.get("audio_sha256") != audio_hash
            or capmeta.get("audio_sha256") != audio_hash
        ):
            raise ValueError("Recording and caption provenance disagree; nothing was published")
        if metadata.get("script_sha256") != capmeta.get("script_sha256"):
            raise ValueError("The caption comparison belongs to a different input script")
        if metadata.get("source_sha256") != episode["source_sha256"]:
            raise ValueError("The recording belongs to a different source revision")
        for identifier, fingerprint in episode["source_sha256"].items():
            if audio.digest(audio.source_article(root, notes[identifier]).encode()) != fingerprint:
                raise ValueError("A source note changed before publication")
        # Inspect the actual media; metadata estimates are never used for listen labels.
        duration = captions.probe_audio(recording / "episode.mp3")
        capfiles = {}
        for name in ("captions.srt", "captions.vtt", "transcript.txt", "cues.json", "words.json"):
            data = (directory / name).read_bytes()
            if audio.digest(data) != capmeta["files"][name]:
                raise ValueError(
                    f"Generated caption file changed: {name}; preserve corrections separately"
                )
            capfiles[name] = data
        cues = json.loads(capfiles["cues.json"])
        if cues.get("audio_sha256") != audio_hash:
            raise ValueError("Caption cues belong to another recording")
        caption_hash = audio.digest(b"\0".join(capfiles[name] for name in sorted(capfiles)))[:16]
        basename = episode["id"] + "-" + audio_hash[:16]
        audio_relative = "assets/audio/" + basename + ".mp3"
        assets[audio_relative] = content
        files = {}
        for kind, extension, data in (
            ("srt", "srt", capfiles["captions.srt"]),
            ("vtt", "vtt", capfiles["captions.vtt"]),
            ("transcript", "txt", capfiles["transcript.txt"]),
            (
                "cues",
                "json",
                (json.dumps(cues["cues"], ensure_ascii=False, indent=2) + "\n").encode(),
            ),
        ):
            relative = f"assets/audio/{basename}-{caption_hash}.{extension}"
            assets[relative] = data
            files[kind] = relative
        publication = episode["publication"]
        note = notes.get(publication.get("note_id"))
        entry = {
            "id": episode["id"],
            "title": episode["title"],
            "kind": publication["kind"],
            "description": note["summary"]
            if note
            else "A listening edition from the Moth & Gravel workbench.",
            "note_id": publication.get("note_id"),
            "slug": note["slug"] if note else None,
            "language": episode["language"],
            "audio": audio_relative,
            "bytes": len(content),
            "audio_sha256": audio_hash,
            "script_sha256": metadata["script_sha256"],
            "source_sha256": episode["source_sha256"],
            "duration_seconds": round(duration, 3),
            "published_at": existing.get(episode["id"], {}).get("published_at", published_at),
            "review_status": "pending",
            "narration": "AI-narrated",
            **files,
            "files_sha256": {
                kind: audio.digest(assets[relative]) for kind, relative in files.items()
            },
        }
        entries.append(entry)
    expected = {n["id"] for n in notes.values()}
    actual = {e["note_id"] for e in entries if e["kind"] == "note"}
    if actual != expected:
        raise ValueError(
            "Every published note must have a completed primary audio edition before releasing the archive"
        )
    for relative, data in assets.items():
        path = root / "docs" / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_bytes() != data:
            raise ValueError("Content-addressed public asset changed; nothing was overwritten")
        path.write_bytes(data)
    audio.write_json(existing_path, entries)
    build_audio.build(root=root)
    build_audio.build(check=True, root=root)
    files = [root / "docs" / p for p in assets] + [
        existing_path,
        root / "docs/notes/podcast.xml",
        root / "docs/notes/index.html",
    ]
    files += [root / "docs/notes" / n["slug"] for n in notes.values()]
    files += [root / "audio/episodes.json", *(root / "audio" / e["script"] for e, _ in completed)]
    hashes = {str(path.relative_to(root)): audio.digest_file(path) for path in files}
    audio.write_json(
        root / "artifacts/audio/release.json",
        {
            "version": 1,
            "phase": "complete",
            "episodes": [e["id"] for e in entries],
            "files": hashes,
        },
    )
    print(f"Prepared {len(entries)} real episodes, subtitles and transcripts for the website.")
    print(
        "Podcast feed: https://mothandgravel.com/notes/podcast.xml (available after the publication PR is merged)"
    )
    return entries


def publish() -> None:
    state = release_state()
    if not state.get("files") or state.get("phase") != "complete":
        raise ValueError("No prepared release. Run make-all first")
    assert_clean_or_prepared()
    build_audio.build(check=True, root=audio.ROOT)
    remote, branch = publication_remote()
    # Never push directly to the deployed main branch.
    if branch in {"main", "master"}:
        branch = "studio/field-notes-listening-" + datetime.now(timezone.utc).strftime(
            "%Y%m%d-%H%M%S"
        )
        git(["switch", "-c", branch])
    paths = dirty_paths()
    if paths:
        git(["add", "--", *paths])
        git(
            [
                "commit",
                "--only",
                "-m",
                "Publish the Field Notes audio collection, subtitles and podcast feed",
                "--",
                *paths,
            ]
        )
    print(f"Push listening assets to {remote}/{branch}.", flush=True)
    git(["push", remote, f"HEAD:refs/heads/{branch}"])
    print("Review or merge the audio publication: https://github.com/mothandgravel/.github/pulls")
    if shutil.which("gh"):
        found = subprocess.run(
            [
                "gh",
                "pr",
                "list",
                "--repo",
                "mothandgravel/.github",
                "--head",
                branch,
                "--state",
                "open",
                "--json",
                "url",
            ],
            cwd=audio.ROOT,
            capture_output=True,
            text=True,
            timeout=30,
        )
        if found.returncode == 0:
            opened = json.loads(found.stdout)
            if opened:
                print(opened[0]["url"])
            else:
                result = subprocess.run(
                    [
                        "gh",
                        "pr",
                        "create",
                        "--repo",
                        "mothandgravel/.github",
                        "--head",
                        branch,
                        "--base",
                        "main",
                        "--title",
                        "Publish the Field Notes listening archive",
                        "--body",
                        "Adds completed AI-narrated recordings, machine-generated subtitles and transcripts, article listening controls, the archive queue and a separate podcast feed. Media hashes and measured durations were validated locally. Transcription remains machine-generated and needs listening review.",
                    ],
                    cwd=audio.ROOT,
                    capture_output=True,
                    text=True,
                    timeout=60,
                )
                if result.returncode == 0:
                    print(result.stdout.strip())
    print(
        "Only completed audio, captions and generated website files were pushed. Cloud credentials and private operation state stay local."
    )


def verify_live() -> None:
    entries = build_audio.load_entries(audio.ROOT)
    if not entries:
        raise ValueError("Prepare and publish the collection before checking the deployed podcast")
    with request.urlopen(build_audio.DOMAIN + "/notes/podcast.xml", timeout=30) as response:
        try:
            feed = ET.fromstring(response.read(1_000_000))
        except ET.ParseError:
            raise ValueError(
                "The deployed podcast feed is not ready; wait for the merged Pages deployment"
            ) from None
    items = {item.findtext("guid"): item for item in feed.findall("./channel/item")}
    if len(items) != len(entries):
        raise ValueError(
            "The deployed feed has a different episode count; wait for the merged Pages deployment"
        )
    for e in entries:
        guid = build_audio.DOMAIN + "/notes/podcast/" + e["id"]
        item = items.get(guid)
        if item is None or item.find("enclosure") is None:
            raise ValueError("A deployed podcast episode has no matching enclosure")
        expected_url = build_audio.DOMAIN + "/" + e["audio"]
        if (
            item is None
            or item.find("enclosure").get("url") != expected_url
            or item.find("enclosure").get("length") != str(e["bytes"])
        ):
            raise ValueError("The deployed feed does not match the prepared recording")
        with request.urlopen(request.Request(expected_url, method="HEAD"), timeout=30) as response:
            if response.headers.get("Content-Length") != str(
                e["bytes"]
            ) or response.headers.get_content_type() not in {"audio/mpeg", "audio/mp3"}:
                raise ValueError("The deployed MP3 has an incorrect length or media type")
        with request.urlopen(
            request.Request(expected_url, headers={"Range": "bytes=0-0"}), timeout=30
        ) as response:
            if (
                response.status != 206
                or response.headers.get("Content-Range") != f"bytes 0-0/{e['bytes']}"
                or len(response.read(2)) != 1
            ):
                raise ValueError(
                    "The media host did not serve a byte-range request; podcast seeking needs investigation"
                )
        for kind in ("vtt", "transcript"):
            with request.urlopen(
                request.Request(build_audio.DOMAIN + "/" + e[kind], method="HEAD"), timeout=30
            ):
                pass
        print(f"Live: {e['id']}; enclosure, length, type, byte range and transcript checked.")
    with request.urlopen(
        request.Request(build_audio.DOMAIN + "/assets/podcast-cover.png", method="HEAD"), timeout=30
    ):
        pass
    print("Podcast ready: https://mothandgravel.com/notes/podcast.xml")


def make_all(args: argparse.Namespace) -> None:
    jobs = getattr(args, "jobs", 3)
    if type(jobs) is not int or not 1 <= jobs <= 8:
        raise ValueError("--jobs must be between 1 and 8")
    if args.publish and not args.dry_run:
        publication_remote()
        assert_clean_or_prepared()
    if not args.dry_run:
        added = sync_catalog()
        if added and args.publish:
            state = release_state()
            files = {**state.get("files", {})}
            for relative in [
                "audio/episodes.json",
                *("audio/scripts/" + identifier + ".txt" for identifier in added),
            ]:
                files[relative] = audio.digest_file(audio.ROOT / relative)
            audio.write_json(
                audio.ROOT / "artifacts/audio/release.json",
                {**state, "version": 1, "phase": "generating", "files": files},
            )
    episodes = json.loads((audio.ROOT / "audio/episodes.json").read_text(encoding="utf-8"))
    published = set(audio.catalog(audio.ROOT))
    primary = {
        e.get("publication", {}).get("note_id")
        for e in episodes
        if e.get("publication", {}).get("kind") == "note"
    }
    if published != primary:
        raise ValueError(
            "The audio catalog is missing a published note; add its source-preserving script before make-all"
        )
    if any(
        not isinstance(e.get("publication"), dict)
        or e["publication"].get("kind") not in {"note", "conversation", "comparison"}
        for e in episodes
    ):
        raise ValueError(
            "Every configured episode needs a note, conversation or comparison publication kind"
        )
    plans = [audio.make_plan(e["id"], args.model, args.endpoint, audio.ROOT) for e in episodes]
    print(
        f"All {len(episodes)} episodes; {len(published)} field notes. Cached work is reused; no automatic uncertain paid retries."
    )
    print(
        f"Estimated synthesis output if all audio is new: ${sum(p['estimated_output_cost_usd'] for p in plans):.4f} USD; text input, transcription and retries extra. Not a spending cap."
    )
    if args.dry_run:
        for plan in plans:
            audio.summarize(plan)
        return
    workflow.ensure_setup(args)
    args._caption_model = workflow.caption_model(args)
    from field_notes_audio.runner import run_episodes

    print(
        f"Process up to {jobs} episodes concurrently; --jobs 1 uses one local worker.",
        flush=True,
    )
    recorder = Timings()
    start = time.perf_counter()
    results = run_episodes(episodes, args, recorder)
    elapsed = time.perf_counter() - start
    completed = [(result.episode, result.directory) for result in results if result.issue is None]
    issues = [
        f"{result.episode['id']}: {result.issue}" for result in results if result.issue is not None
    ]
    timing_path = audio.ROOT / "artifacts/audio/processing-times.json"
    audio.write_json(
        timing_path,
        {
            "version": 1,
            "jobs": jobs,
            "model": args.model,
            "endpoint": args.endpoint,
            "wall_seconds": round(elapsed, 4),
            "episode_seconds": {
                result.episode["id"]: round(result.seconds, 4) for result in results
            },
            "stages": recorder.events(),
        },
    )
    print(f"Batch processing: {elapsed:.1f}s wall time. Stage timings: {timing_path}")
    if issues:
        print("\nSaved progress; remaining work:")
        for issue in issues:
            print(issue)
        raise RuntimeError(
            "The collection is incomplete. Repeat make-all to resume. No partial collection was published."
        )
    prepare_publication(completed)
    if args.publish:
        publish()
    else:
        print(
            "Ready for review. To push the prepared collection: python3 scripts/field_audio.py publish"
        )


def add_arguments(commands: argparse._SubParsersAction) -> None:
    sub = commands.add_parser(
        "make-all", help="Generate/reuse every episode, subtitle it and build the listening archive"
    )
    sub.add_argument("--project")
    sub.add_argument("--bucket")
    sub.add_argument("--endpoint", choices=audio.ENDPOINTS)
    sub.add_argument("--location", choices=("us", "eu"))
    sub.add_argument("--model", choices=audio.MODELS)
    sub.add_argument("--auth", choices=("gcloud", "adc"))
    sub.add_argument("--wait", type=int, default=900)
    sub.add_argument(
        "--jobs", type=int, default=3, help="Concurrent episode pipelines, 1–8; default 3"
    )
    sub.add_argument("--retry-uncertain", action="store_true")
    sub.add_argument("--restart-failed", action="store_true")
    sub.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate and estimate offline without setup or generation",
    )
    sub.add_argument(
        "--publish",
        action="store_true",
        help="Commit/push the completed site assets to a PR branch",
    )
    commands.add_parser(
        "publish", help="Commit/push a previously prepared complete listening collection"
    )
    commands.add_parser(
        "sync", help="Prepare source-preserving scripts for newly published notes, offline"
    )
    commands.add_parser(
        "verify-live", help="Check the deployed podcast, MP3 HEAD/byte ranges and transcript links"
    )
