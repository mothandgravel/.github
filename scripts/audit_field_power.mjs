import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import axe from 'axe-core';
import { launchAuditBrowser } from './audit_browser.mjs';
const origin=process.env.SITE_URL??'http://127.0.0.1:8793';
const out='artifacts/design-review/field-power';
await mkdir(out,{recursive:true});
const browser=await launchAuditBrowser();
const results=[];
try {
  for(const [width,theme] of [[1440,'night'],[390,'afterlight']]) {
    const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'});
    const errors=[],writes=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))writes.push(r.url());});
    await page.addInitScript(t=>localStorage.setItem('moth-and-gravel-theme',t),theme);
    await page.goto(`${origin}/specimens/field-power/`);
    await page.locator('#fp-scene svg').waitFor();
    await page.screenshot({path:`${out}/${width}-${theme}-opening.png`});
    assert.equal(await page.locator('#fp-energy').innerText(),'21.08');
    await page.locator('#fp-trip').click();
    assert.equal(await page.locator('#fp-unmet').innerText(),'2.0 kW');
    await page.locator('[data-load="workshop"]').click();
    assert.equal(await page.locator('#fp-unmet').innerText(),'0.0 kW');
    await page.locator('[data-minute="10"]').click();
    await page.locator('#fp-inspect').click();
    await page.locator('#fp-request').click();
    await page.locator('#fp-approve').click();
    assert.match(await page.locator('#fp-receipt-list').innerText(),/Still in transit/);
    await page.locator('[data-minute="34"]').click();
    assert.match(await page.locator('#fp-receipt-list').innerText(),/expired/);
    await page.locator('#fp-request').click();
    await page.locator('#fp-approve').click();
    assert.equal(await page.locator('#fp-generator').innerText(),'warming');
    await page.locator('[data-minute="42"]').click();
    assert.equal(await page.locator('#fp-generator').innerText(),'online');
    assert.equal(await page.locator('.fp-receipt').count(),2);
    const downloadEvent=page.waitForEvent('download');
    await page.locator('#fp-export').click();
    const download=await downloadEvent, file=`${out}/${width}-account.json`;
    await download.saveAs(file);
    const data=JSON.parse(await readFile(file,'utf8'));
    assert.equal(data.signed,false); assert.equal(data.current.receipts[0].outcome,'expired');
    assert.equal(data.current.receipts[1].outcome,'applied');
    await page.locator('#fp-example').click();
    assert.equal(await page.locator('#fp-account option').count(),2);
    await page.locator('[data-minute="34"]').click();
    assert.equal(await page.locator('[data-load="water"]').isDisabled(),true);
    const captureStyle='.site-header,.skip-link{visibility:hidden!important}';
    await page.locator('#fp-bench').screenshot({path:`${out}/${width}-${theme}-bench.png`,style:captureStyle});
    await page.locator('.fp-recovery').screenshot({path:`${out}/${width}-${theme}-receipt.png`,style:captureStyle});
    await page.locator('#fp-fork').click();
    assert.equal(await page.locator('[data-load="water"]').isDisabled(),false);
    await page.locator('[data-load="water"]').click();
    await page.locator('#fp-account').selectOption('1');
    assert.match(await page.locator('#fp-load-state-water').innerText(),/Shed locally/);
    await page.locator('#fp-account').selectOption('2');
    assert.match(await page.locator('#fp-load-state-water').innerText(),/3.0 kW served/);
    await page.locator('[data-equipment="generator"]').click();
    assert.match(await page.locator('#fp-equipment-title').innerText(),/Starting is not supplying/);
    await page.locator('#fp-scrub').focus(); await page.keyboard.press('Home');
    assert.equal(await page.locator('#fp-minute').innerText(),'0');
    await page.keyboard.press('ArrowRight'); assert.equal(await page.locator('#fp-minute').innerText(),'1');
    await page.locator('#fp-capacity').selectOption('20');
    await page.locator('#fp-temperature').selectOption('-20');
    await page.locator('#fp-settings button').click();
    assert.equal(await page.locator('#fp-energy').innerText(),'9.42');
    assert.equal(await page.locator('#fp-account option').count(),4);
    await page.locator('#fp-play').click();
    await page.waitForFunction(()=>Number(document.getElementById('fp-minute').textContent)>0);
    await page.locator('#fp-play').click();
    const minute=await page.locator('#fp-minute').innerText();
    await page.waitForTimeout(800);
    assert.equal(await page.locator('#fp-minute').innerText(),minute);
    await page.addScriptTag({content:axe.source});
    const a=await page.evaluate(async()=>axe.run(document.querySelector('main'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
    assert.deepEqual(a.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    assert.equal(overflow,false); assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);
    if(width===390){
      await page.setViewportSize({width:320,height:850});
      await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
      const size=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,large:[...document.querySelectorAll('main *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1&&e.tagName!==e.tagName.toLowerCase()).map(e=>({tag:e.tagName,id:e.id,w:e.getBoundingClientRect().width}))}));
      assert.equal(size.scroll<=size.width,true,JSON.stringify(size));
    }
    results.push({width,theme,errors,writes,axeViolations:a.violations.length,overflow,manualRecovery:'expired then applied',branch:'original retained',export:'verified'});
    await page.close();
  }
  await writeFile(`${out}/audit.json`,JSON.stringify(results,null,2)+'\n');
  console.log(JSON.stringify(results,null,2));
} finally {await browser.close();}
