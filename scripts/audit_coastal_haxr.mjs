import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import axe from "axe-core";
import { launchAuditBrowser } from "./audit_browser.mjs";
const origin = process.env.SITE_URL ?? "http://127.0.0.1:8793";
const output = "artifacts/design-review";
await mkdir(output, { recursive: true });
const browser = await launchAuditBrowser();
const results = [];
try {
  for (const [width, theme] of [[1440, "night"], [390, "afterlight"]]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: "reduce" });
    const errors = [], writes = [], dataRequests = [];
    page.on("pageerror", e => errors.push(e.message));
    page.on("request", r => {
      if (!["GET", "HEAD"].includes(r.method())) writes.push(r.method());
      if (r.url().includes("/data/haxr/")) dataRequests.push(r.url());
    });
    await page.addInitScript(t => localStorage.setItem("moth-and-gravel-theme", t), theme);
    await page.goto(`${origin}/specimens/coastal-watch/radar-replay/`);
    assert.equal(dataRequests.length, 0, "Recordings should load only on request");
    await page.screenshot({ path: `${output}/coastal-haxr-${width}-${theme}-opening.png` });
    await page.locator("#hx-load").click();
    await page.locator("#hx-workspace").waitFor({ state: "visible" });
    assert.equal(dataRequests.length, 2);
    assert.match(await page.locator("#hx-pair-status").innerText(), /No eligible pair/);
    assert.match(await page.locator("#hx-pair-summary").innerText(), /10 \/ 16/);
    assert.match(await page.locator("#hx-contact-count").innerText(), /10 in both · 1 upstream/);
    assert.equal(await page.locator(".hx-ais-mark[data-selected=true]").count(), 2);
    await page.locator(".hx-radars").screenshot({ path: `${output}/coastal-haxr-${width}-${theme}-stations.png` });
    const canvasBefore = await page.locator("#hx-reiherstieg-canvas").evaluate(e => e.toDataURL());
    await page.locator("#hx-tolerance").focus();
    await page.keyboard.press("End");
    assert.match(await page.locator("#hx-pair-summary").innerText(), /16 \/ 16/);
    assert.match(await page.locator("#hx-pair-status").innerText(), /Within the chosen bound/);
    assert.equal(await page.locator("#hx-reiherstieg-canvas").evaluate(e => e.toDataURL()), canvasBefore);
    await page.locator("#hx-tolerance").press("Home");
    assert.match(await page.locator("#hx-pair-summary").innerText(), /0 \/ 16/);
    await page.locator("#hx-tolerance").fill("2");
    await page.locator("#hx-tolerance").dispatchEvent("input");
    await page.locator(".hx-clock").screenshot({ path: `${output}/coastal-haxr-${width}-${theme}-timing.png` });
    const uid = await page.locator("#hx-contact").inputValue();
    await page.locator("#hx-next").click();
    assert.equal(await page.locator("#hx-frame").inputValue(), "1");
    assert.equal(await page.locator("#hx-contact").inputValue(), uid);
    await page.locator("#hx-anchor").selectOption("hohe_schaar");
    assert.equal(await page.locator("#hx-hohe_schaar-role").textContent(), "Anchor station");
    await page.locator("#hx-ais").uncheck();
    assert.equal(await page.locator(".hx-ais-mark").count(), 0);
    await page.locator("#hx-ais").check();
    await page.locator("#hx-cell-station").selectOption("hohe_schaar");
    await page.locator("#hx-col").fill("0"); await page.locator("#hx-row").fill("127");
    await page.locator("#hx-inspect").click();
    assert.match(await page.locator("#hx-cell-result").innerText(), /Hohe Schaar, column 0, row 127/);
    await page.locator("#hx-col").fill("128"); await page.locator("#hx-inspect").click();
    assert.match(await page.locator("#hx-cell-result").innerText(), /whole-number/);
    await page.locator("#hx-reiherstieg-scope").click({ position: { x: 30, y: 30 } });
    assert.equal(await page.locator("#hx-cell-station").inputValue(), "reiherstieg");
    const downloadEvent = page.waitForEvent("download");
    await page.locator("#hx-export").click();
    const download = await downloadEvent;
    const exported = JSON.parse(await readFile(await download.path(), "utf8"));
    assert.equal(exported.selection.uid, uid);
    assert.equal(exported.selection.anchor, "hohe_schaar");
    assert.equal(exported.selectedBin.station, "reiherstieg");
    assert.equal(exported.sourceLineage.family, "one shared AIS stream");
    await page.locator("#hx-frame").fill("14"); await page.locator("#hx-frame").dispatchEvent("input");
    await page.locator("#hx-play").click();
    await page.waitForFunction(() => document.getElementById("hx-frame").value === "15");
    assert.equal(await page.locator("#hx-play").getAttribute("aria-pressed"), "false");
    await page.addScriptTag({ content: axe.source });
    const audit = await page.evaluate(() => axe.run(document.querySelector("main"), { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21aa"] } }));
    const violations = audit.violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }));
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    results.push({ width, theme, errors, writes, overflow, violations });
    await writeFile(`${output}/coastal-haxr-audit.json`, JSON.stringify(results, null, 2));
    assert.deepEqual(errors, []); assert.deepEqual(writes, []); assert.equal(overflow, false);
    assert.deepEqual(violations, []);
    await page.close();
  }
  const page = await browser.newPage();
  await page.route("**/data/haxr/reiherstieg.json", route => route.fulfill({ body: "{}", contentType: "application/json" }));
  await page.goto(`${origin}/specimens/coastal-watch/radar-replay/`);
  await page.locator("#hx-load").click();
  await page.waitForFunction(() => document.getElementById("hx-load-status").textContent.includes("does not match its published hash"));
  assert.equal(await page.locator("#hx-workspace").isVisible(), false);
  assert.equal(await page.locator("#hx-load").isEnabled(), true);
  await page.unroute("**/data/haxr/reiherstieg.json");
  await page.locator("#hx-load").click();
  await page.locator("#hx-workspace").waitFor({ state: "visible" });
  await page.close();
  console.log("HAXR desk: desktop/mobile, recorded data integrity, pairing, lineage, bin inspection, export, playback, accessibility and failed-load retry passed.");
} finally { await browser.close(); }
