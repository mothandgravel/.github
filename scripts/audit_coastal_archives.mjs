import assert from 'node:assert/strict';
import {mkdir, writeFile, readFile} from 'node:fs/promises';
import axe from 'axe-core';
import {launchAuditBrowser} from './audit_browser.mjs';

const origin = process.env.SITE_URL ?? 'http://127.0.0.1:8793';
const out = 'artifacts/design-review/coastal-archives'; await mkdir(out, {recursive: true});
const browser = await launchAuditBrowser();
try {
  for (const [width, theme] of [[1440, 'night'], [1440, 'afterlight'], [390, 'afterlight'], [390, 'night'], [320, 'night'], [320, 'afterlight']]) {
    const page = await browser.newPage({viewport: {width, height: 1080}, reducedMotion: 'reduce'}), errors = [], violations = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(t => localStorage.setItem('moth-and-gravel-theme', t), theme);
    await page.goto(origin + '/specimens/coastal-watch/source-notebook/#ca-study');
    await page.locator('#ca-desk').waitFor({state: 'visible'});
    assert.equal(await page.locator('audio,video').count(), 0);
    assert.equal(await page.locator('#ca-local').textContent(), '12:00');
    assert.match(await page.locator('#ca-receipt-clock').textContent(), /2026-11-11T10:00:00Z/);
    await page.locator('#ca-minute').focus(); await page.keyboard.press('ArrowLeft');
    assert.equal(await page.locator('#ca-local').textContent(), '11:59');
    assert.equal(await page.locator('#ca-radar-empty').isVisible(), true);
    assert.equal(await page.locator('#ca-weather-map image').getAttribute('visibility'), 'hidden');
    assert.equal(await page.locator('#ca-original').isVisible(), false);
    await page.locator('#ca-find-radar').click();
    assert.equal(await page.locator('.ca-scan[aria-pressed=true]').evaluate(el => el === document.activeElement), true);
    await page.locator('.ca-scan').nth(3).click();
    assert.equal(await page.locator('#ca-local').textContent(), '12:15');
    assert.equal(await page.locator('.ca-scan[aria-pressed=true]').count(), 1);
    await page.locator('#ca-minute').focus(); await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#ca-radar-empty').isVisible(), true);
    await page.locator('#ca-find-radar').click();
    await page.locator('.ca-pixel-details summary').click();
    await page.waitForFunction(() => /Code/.test(document.getElementById('ca-pixel-value').textContent));
    assert.match(await page.locator('#ca-pixel-value').textContent(), /10:00 UTC/);
    const pixels = await readFile(new URL('../docs/data/coastal-archives/2026-11-11/fmi-radar-1000-gulf.bin', import.meta.url));
    for (const masked of [true, false]) {
      const at = pixels.findIndex(p => masked ? p === 0 : p !== 0);
      await page.locator('#ca-pixel-x').fill(String(at % 1100)); await page.locator('#ca-pixel-y').fill(String(Math.floor(at / 1100)));
      await page.waitForFunction(() => !/Opening/.test(document.getElementById('ca-pixel-value').textContent));
      const value = await page.locator('#ca-pixel-value').textContent();
      if (masked) assert.match(value, /Code 0.*Physical value unknown/); else assert.ok(value.includes(`Code ${pixels[at]} × 0.5 − 32 = ${pixels[at] * .5 - 32} dBZ`));
    }
    await page.locator('#ca-pixel-x').fill('1100');
    assert.match(await page.locator('#ca-pixel-value').textContent(), /0–1099/);
    await page.locator('#ca-pixel-x').fill('400');
    await page.locator('#ca-play').click();
    await page.waitForFunction(() => /End of the preserved strip/.test(document.getElementById('ca-replay-status').textContent));
    assert.equal(await page.locator('#ca-play').getAttribute('aria-pressed'), 'false');
    assert.equal(await page.locator('#ca-local').textContent(), '12:15');
    await page.locator('#ca-play').click();
    await page.locator('[data-view=gauges]').click();
    assert.equal(await page.locator('#ca-play').getAttribute('aria-pressed'), 'false');
    assert.equal(await page.locator('.ca-gauge-card').count(), 3);
    assert.match(await page.locator('#ca-gauge-arithmetic').textContent(), /÷ 100 − 5 = [\d.-]+\.\d{5} m/);
    assert.equal(await page.locator('.ca-gauge-selected').count(), 3);
    await page.locator('[data-gauge="26045"]').click();
    assert.match(await page.locator('#ca-gauge-station').textContent(), /KUNDA/);
    await page.locator('#ca-parameter').selectOption('WT avg');
    assert.match(await page.locator('#ca-gauge-arithmetic').textContent(), /°C.*hourly mean/);
    await page.locator('#ca-parameter').selectOption('WL avg');
    await page.locator('#ca-gauges details summary').click();
    assert.equal(await page.locator('#ca-gauge-rows tr').count(), 24);
    assert.equal(await page.locator('#ca-gauge-rows tr[aria-current=true]').count(), 1);
    for (const view of ['gauges', 'reports', 'radar', 'imagery']) {
      await page.locator(`[data-view=${view}]`).click();
      if (view === 'radar') await page.waitForFunction(() => document.querySelector('#ca-weather-map image').getAttribute('visibility') === 'visible');
      await page.addScriptTag({content: axe.source});
      const result = await page.evaluate(async () => axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']}}));
      violations.push(...result.violations.map(v => ({view, id: v.id, impact: v.impact, nodes: v.nodes.map(n => n.target)})));
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${view} overflow at ${width}`);
      await page.locator('.ca-coverage').scrollIntoViewIfNeeded();
      await page.screenshot({path: `${out}/${view}-${width}-${theme}.png`});
      await page.locator(`#ca-${view}`).scrollIntoViewIfNeeded();
      await page.screenshot({path: `${out}/${view}-scene-${width}-${theme}.png`});
    }
    await page.locator('[data-view=reports]').click(); await page.locator('#ca-minute').press('Home');
    assert.equal(await page.locator('#ca-report-raw').textContent(), 'No earlier report saved.');
    assert.equal(await page.locator('#ca-original').isVisible(), false);
    await page.locator('#ca-report-next').click();
    assert.equal(await page.locator('#ca-local').textContent(), '00:20');
    assert.match(await page.locator('#ca-report-raw').textContent(), /EFHK 102220Z/);
    await page.locator('#ca-airport').selectOption('EETN');
    assert.match(await page.locator('#ca-report-raw').textContent(), /EETN 102220Z/);
    await page.locator('#ca-receipt-details summary').click();
    const receipt = JSON.parse(await page.locator('#ca-receipt-json').textContent());
    assert.equal(receipt.originalReceiverTime, null); assert.equal(receipt.firstPublication, null);
    assert.match(receipt.httpReceipt.completedAt, /^2026-11-13/);
    const download = page.waitForEvent('download'); await page.locator('#ca-export').click();
    assert.match((await download).suggestedFilename(), /coastal-watch-reports/);
    for (const id of ['ca-original', 'ca-http']) assert.equal((await page.request.get(await page.locator('#' + id).getAttribute('href'))).status(), 200);
    await page.locator('[data-view=imagery]').click();
    await page.locator('[data-image=aqua]').click();
    const daily = JSON.parse(await page.locator('#ca-receipt-json').textContent());
    assert.equal(daily.sourceTime, '2026-11-11'); assert.equal(daily.record.acquiredAt, null);
    assert.equal(daily.browseTimeUtc, null); assert.equal(daily.browseTimeApplies, false);
    assert.equal(await page.locator('#ca-receipt-details>summary').evaluate(el => el === document.activeElement), true);
    await page.locator('#ca-minute').press('End');
    assert.equal(await page.locator('#ca-local').textContent(), '23:59');
    assert.equal(JSON.parse(await page.locator('#ca-receipt-json').textContent()).record.acquiredAt, null);
    assert.equal(await page.locator('#ca-study').getAttribute('data-daily'), 'true');
    await page.locator('.ca-image-plates').scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('.ca-image-plate img')].every(img => img.complete && img.naturalWidth === 1100));
    assert.equal(await page.locator('#cs-hour-label').textContent(), '23:00 EET');
    await page.locator('#cs-hour').press('Home');
    assert.equal(await page.locator('#ca-local').textContent(), '00:00');
    await writeFile(`${out}/audit-${width}-${theme}.json`, JSON.stringify({width, theme, errors, violations}, null, 2));
    assert.deepEqual(errors, []); assert.deepEqual(violations, []);
    await page.close(); console.log(`Four archives ${width}/${theme}: clocks, mask, bounded replay, raw messages, export, images and WCAG passed`);
  }
  const page = await browser.newPage({viewport: {width: 390, height: 1000}, reducedMotion: 'reduce'});
  let notebookAvailable = false, imageAvailable = false, pixelsAvailable = false;
  await page.route('**/coastal-archives/2026-11-11/notebook.json', route => notebookAvailable ? route.continue() : route.fulfill({status: 503, body: 'Test archive temporarily unavailable'}));
  await page.route('**/fmi-radar-1000-gulf.png', route => imageAvailable ? route.continue() : route.fulfill({status: 404, body: 'Test image unavailable'}));
  await page.route('**/fmi-radar-1000-gulf.bin', route => pixelsAvailable ? route.continue() : route.fulfill({status: 503, body: 'Test pixel file unavailable'}));
  await page.goto(origin + '/specimens/coastal-watch/source-notebook/#ca-study');
  await page.locator('#ca-retry').waitFor({state: 'visible'});
  assert.match(await page.locator('#ca-loading').textContent(), /could not open/);
  notebookAvailable = true; await page.locator('#ca-retry').click();
  await page.locator('#ca-radar-error').waitFor({state: 'visible'});
  assert.match(await page.locator('#ca-radar-image-status').textContent(), /could not be opened/);
  assert.equal(await page.locator('#ca-weather-map image').getAttribute('visibility'), 'hidden');
  assert.match(await page.locator('#ca-receipt-clock').textContent(), /2026-11-11T10:00:00Z/);
  imageAvailable = true; await page.locator('#ca-retry-image').click();
  await page.waitForFunction(() => document.querySelector('#ca-weather-map image').getAttribute('visibility') === 'visible');
  assert.equal(await page.locator('#ca-radar-error').isVisible(), false);
  await page.locator('.ca-pixel-details summary').click();
  await page.locator('#ca-retry-pixel').waitFor({state: 'visible'});
  assert.match(await page.locator('#ca-pixel-value').textContent(), /No cell value inferred/);
  pixelsAvailable = true; await page.locator('#ca-retry-pixel').click();
  await page.waitForFunction(() => /Code/.test(document.getElementById('ca-pixel-value').textContent));
  await page.locator('#ca-receipt-details summary').click();
  await page.addScriptTag({content: axe.source});
  for (const state of ['details-open', 'empty-radar', 'before-first-report']) {
    if (state === 'empty-radar') await page.locator('#ca-minute').press('Home');
    if (state === 'before-first-report') await page.locator('[data-view=reports]').click();
    const result = await page.evaluate(async () => axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']}}));
    assert.deepEqual(result.violations.map(v => ({id: v.id, nodes: v.nodes.map(n => n.target)})), [], state);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, state);
  }
  await writeFile(`${out}/failure-recovery.json`, JSON.stringify({notebookRetry: true, imageFailureDistinctFromMask: true, pixelRetry: true, absentStatesAndOpenDetailsWcag: true}, null, 2));
  await page.close(); console.log('Four archives: failed notebook/image/pixel downloads recover without fabricated values; absent states and open receipts pass WCAG');
} finally { await browser.close(); }
