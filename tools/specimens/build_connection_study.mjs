/** Emit the selected source helper with types removed; no product runtime is loaded. */
import { stripTypeScriptTypes } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const sourceURL = new URL('./source/quality-measurement-status.ts', import.meta.url);
const outputURL = new URL('../../docs/assets/specimens/measurement-status.mjs', import.meta.url);
const provenanceURL = new URL('../../design/connection-study-provenance.json', import.meta.url);
const source = await readFile(sourceURL, 'utf8');
const hash = value => createHash('sha256').update(value).digest('hex');
const provenance = JSON.parse(await readFile(provenanceURL, 'utf8'));
if (hash(source) !== provenance.helper.sourceSha256) throw new Error('Selected source differs from provenance');
const output = '// Generated by tools/specimens/build_connection_study.mjs.\n' + stripTypeScriptTypes(source).replace(/[ \t]+$/gm, '');
if (process.argv.includes('--check')) {
  if (output !== await readFile(outputURL, 'utf8')) throw new Error('Stale measurement helper; run tools/specimens/build_connection_study.mjs');
} else {
  await writeFile(outputURL, output);
}
